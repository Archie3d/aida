#!/usr/bin/env python3
"""Generate pinned Ada 2005 Unicode properties (no network during builds).

Usage: generate_unicode.py UnicodeData-4.0.0.txt SpecialCasing-4.0.0.txt output
Official inputs: https://www.unicode.org/Public/4.0-Update/
"""
import hashlib
import pathlib
import sys

source, special, output = map(pathlib.Path, sys.argv[1:])
properties = []
upper = {}
lower = {}
pending = None
for line in source.read_text().splitlines():
    fields = line.split(';')
    code = int(fields[0], 16)
    category = fields[2]
    flags = (1 if category in ('Lu', 'Ll', 'Lt', 'Lm', 'Lo', 'Nl') else 0)
    flags |= 2 if category in ('Mn', 'Mc', 'Nd', 'Pc', 'Cf') else 0
    flags |= 4 if category == 'Pc' else 0
    flags |= 8 if category == 'Cf' else 0
    flags |= 16 if category == 'Zs' else 0
    flags |= 32 if category not in ('Cc', 'Co', 'Cs', 'Zl', 'Zp') else 0
    if fields[1].endswith(', First>'):
        pending = code
    else:
        low = pending if fields[1].endswith(', Last>') else code
        properties.append((low, code, flags))
        pending = None
    if fields[13]:
        lower[code] = int(fields[13], 16)
    if fields[12]:
        upper[code] = [int(fields[12], 16)]
for line in special.read_text().splitlines():
    fields = line.split('#')[0].strip().split(';')
    if len(fields) >= 5 and not fields[4].strip():
        upper[int(fields[0], 16)] = [int(c, 16) for c in fields[3].split()]
ranges = []
for low, high, flags in properties:
    if ranges and ranges[-1][1] + 1 == low and ranges[-1][2] == flags:
        ranges[-1] = ranges[-1][0], high, flags
    else:
        ranges.append((low, high, flags))
text = '// Generated by scripts/generate_unicode.py; Unicode 4.0.0.\n'
for p in (source, special):
    text += '// ' + p.name + ' SHA-256: ' + hashlib.sha256(p.read_bytes()).hexdigest() + '\n'
text += '''#pragma once
#include <stdint.h>

typedef struct
{
    uint32_t low;
    uint32_t high;
    unsigned flags;
} AdaUnicodeRange;

static const AdaUnicodeRange kAdaUnicodeRanges[] = {
'''
text += ''.join(f'    {{ 0x{a:X}, 0x{b:X}, {f} }},\n' for a, b, f in ranges)
text += '''};

typedef struct
{
    uint32_t code;
    uint32_t upper[3];
    unsigned length;
} AdaUnicodeCase;

static const AdaUnicodeCase kAdaUnicodeUpper[] = {
'''
for code, mapping in sorted(upper.items()):
    if mapping == [code]:
        continue
    assert len(mapping) <= 3
    values = mapping + [0] * (3 - len(mapping))
    text += f'    {{ 0x{code:X}, {{ ' + ', '.join(f'0x{x:X}' for x in values) + f' }}, {len(mapping)} }},\n'
text += '};\n'
text += '\ntypedef struct\n{\n    uint32_t code;\n    uint32_t lower;\n} AdaUnicodeLowerCase;\n\n'
text += 'static const AdaUnicodeLowerCase kAdaUnicodeLower[] = {\n'
for code, mapped in sorted(lower.items()):
    text += f'    {{ 0x{code:X}, 0x{mapped:X} }},\n'
text += '};\n'
output.write_text(text)
