#!/usr/bin/env python3
"""Generate deterministic terminal widths using Python's Unicode database.

Run with Python's Unicode 17.0.0 database to reproduce the checked-in table.
Ambiguous characters occupy one cell; emoji sequences are rendered by scalar.
"""
import pathlib
import unicodedata

assert unicodedata.unidata_version == "17.0.0", unicodedata.unidata_version
ranges = []
for code in range(0x110000):
    char = chr(code)
    category = unicodedata.category(char)
    width = -1 if category == "Cf" else 0 if category in ("Mn", "Me") else (
        2 if category != "Cn" and unicodedata.east_asian_width(char) in ("W", "F") else 1)
    if width == 1:
        continue
    if ranges and ranges[-1][1] + 1 == code and ranges[-1][2] == width:
        ranges[-1] = (ranges[-1][0], code, width)
    else:
        ranges.append((code, code, width))
output = pathlib.Path(__file__).resolve().parents[1] / "adac" / "DiagnosticWidth.h"
output.write_text('''// Generated by tools/generate_diagnostic_width.py; Unicode 17.0.0.
#pragma once

#include <cstdint>

namespace DiagnosticWidth {
struct Range
{
    uint32_t low;
    uint32_t high;
    int width;
};
inline constexpr Range kRanges[] = {
''' + ''.join(f'    {{ 0x{low:X}, 0x{high:X}, {width} }},\n' for low, high, width in ranges) + '''};

inline int cells(uint32_t code)
{
    unsigned low = 0, high = sizeof(kRanges) / sizeof(kRanges[0]);
    while (low < high) {
        unsigned middle = low + (high - low) / 2;
        const Range& range = kRanges[middle];
        if (code < range.low) { high = middle; }
        else if (code > range.high) { low = middle + 1; }
        else { return range.width; }
    }
    return 1;
}
} // namespace DiagnosticWidth
''')
